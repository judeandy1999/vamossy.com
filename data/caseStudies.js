// Helper functions for filtering and searching
export const getCaseStudyById = (id) => {
  return caseStudies.find(study => study.id === id);
};

export const searchCaseStudies = (query) => {
  if (!query) return caseStudies;
  
  const lowercaseQuery = query.toLowerCase();
  return caseStudies.filter(study => 
    study.title.toLowerCase().includes(lowercaseQuery) ||
    study.category.toLowerCase().includes(lowercaseQuery) ||
    study.industry.toLowerCase().includes(lowercaseQuery) ||
    study.summary.toLowerCase().includes(lowercaseQuery) ||
    study.tags.some(tag => tag.toLowerCase().includes(lowercaseQuery))
  );
};

export const getCaseStudiesByCategory = (category) => {
  return caseStudies.filter(study => study.category === category);
};

export const getCaseStudiesByIndustry = (industry) => {
  return caseStudies.filter(study => study.industry === industry);
};

